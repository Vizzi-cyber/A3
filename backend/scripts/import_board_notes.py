def import_board_notes():
    db = os.path.abspath(DB_PATH)
    print(f"数据库路径: {db}")
    conn = sqlite3.connect(db)
    cur = conn.cursor()

    for kp_id, board_content in BOARD_NOTES.items():
        cur.execute("SELECT document FROM knowledge_points WHERE kp_id=?", (kp_id,))
        row = cur.fetchone()
        if not row:
            print(f"  [SKIP] {kp_id}: 不存在")
            continue

        existing_doc = row[0] or ""
        # 在现有文档末尾追加板书内容
        new_doc = existing_doc.rstrip() + "\n" + board_content.strip() + "\n"
        cur.execute("UPDATE knowledge_points SET document=? WHERE kp_id=?", (new_doc, kp_id))
        print(f"  [OK] {kp_id}: 追加板书笔记 ({len(board_content)} 字符)")

    conn.commit()
    conn.close()
    print(f"\n完成！共更新 {len(BOARD_NOTES)} 个知识点的板书笔记。")


if __name__ == "__main__":
    import_board_notes()
